/**
 * The browser's stylesheet and its English wording against the shared design of the Proof of Trust
 * (`PROOF_OF_TRUST_DESIGN`, `PROOF_OF_TRUST_COPY` in the core): the Ayni app draws the same card from them.
 */
import {
  PROOF_OF_TRUST_COLORS as C,
  PROOF_OF_TRUST_DESIGN as D,
  PROOF_OF_TRUST_COPY,
  TRUST_COPY,
  VERDICT_MARK,
} from '@ayni.org/ayni-ui-core'
import { describe, expect, it } from 'vitest'
import en from '../src/i18n/en.json'
import { em, pct, px, role, rule, tint } from './stylesheet.js'

const at = (tree: unknown, path: string): unknown =>
  path.split('.').reduce<unknown>((node, key) => (node as Record<string, unknown> | undefined)?.[key], tree)

describe('the stylesheet follows the shared design of the Proof of Trust', () => {
  it('the card and its head', () => {
    expect(rule('.pot-view').background).toBe(role(C.view.background))
    const card = rule('.pot')
    expect(card.width).toBe(`min(${px(D.card.maxWidth)}, 100%)`)
    expect(card['border-radius']).toBe(px(D.card.radius))
    expect(card.background).toBe(role(C.card.background))
    expect(card.border).toBe(`1px solid ${role(C.card.border)}`)
    const head = rule('.pot-head')
    const h = D.head
    expect(head.gap).toBe(px(h.gap))
    expect(head.padding).toBe(`${px(h.paddingY)} ${px(h.paddingRight)} ${px(h.paddingY)} ${px(h.paddingLeft)}`)
    expect(head['border-bottom']).toBe(`1px solid ${role(C.card.border)}`)
    expect(rule('.pot-dot').width).toBe(px(h.dotSize))
    expect(rule('.pot-dot').height).toBe(px(h.dotSize))
    for (const [verdict, { color }] of Object.entries(VERDICT_MARK))
      expect(rule(`.pot-dot.${verdict}`).background).toBe(role(color))
    expect(rule('.pot-did')['font-size']).toBe(px(h.didFontSize))
    expect(rule('.pot-did').color).toBe(role(C.did.text))
    const body = rule('.pot-body')
    expect(body.padding).toBe(`${px(D.body.paddingTop)} ${px(D.body.paddingX)} ${px(D.body.paddingBottom)}`)
    expect(body.gap).toBe(px(D.body.gap))
  })

  it('the verdict', () => {
    const v = D.verdict
    const verdict = rule('.pot-verdict')
    expect(verdict.gap).toBe(px(v.gap))
    expect(verdict.padding).toBe(`${px(v.paddingY)} ${px(v.paddingX)}`)
    expect(verdict['border-radius']).toBe(px(v.radius))
    expect(verdict.border).toBe(`${px(v.borderWidth)} solid var(--border)`)
    for (const [name, { color }] of Object.entries(VERDICT_MARK)) {
      const one = rule(`.pot-verdict.${name}`)
      expect(one['border-color']).toBe(role(color))
      expect(one.color).toBe(role(color))
      expect(one.background).toBe(tint(color, v.tint))
    }
    const label = rule('.pot-verdict-label')
    expect(label['font-size']).toBe(px(v.labelFontSize))
    expect(label['font-weight']).toBe(String(v.labelWeight))
    expect(label['letter-spacing']).toBe(em(v.labelSpacing))
    expect(rule('.pot-verdict-sub')['font-size']).toBe(px(v.subFontSize))
    expect(rule('.pot-verdict-sub').color).toBe(role(C.verdictSub.text))
    expect(rule('.pot-reasons')['font-size']).toBe(px(D.reasons.fontSize))
    expect(rule('.pot-reasons')['padding-left']).toBe(px(D.reasons.paddingLeft))
    expect(rule('.pot-reasons').color).toBe(role(C.reasons.text))
    expect(rule('.pot-loading').gap).toBe(px(D.loading.gap))
    expect(rule('.pot-loading')['font-size']).toBe(px(D.loading.fontSize))
    expect(rule('.pot-loading').color).toBe(role(C.loading.text))
  })

  it('an identity step: its node, its line, who it names', () => {
    const step = rule('.pot-step')
    expect(step.gap).toBe(px(D.step.gap))
    expect(step['padding-bottom']).toBe(px(D.step.paddingBottom))
    expect(rule('.pot-step-body').gap).toBe(px(D.step.bodyGap))
    const line = rule('.pot-step:not(:last-child)::before')
    expect(line.left).toBe(px(D.line.left))
    expect(line.top).toBe(px(D.line.top))
    expect(line.width).toBe(px(D.line.width))
    expect(line.background).toBe(`color-mix(in srgb, ${role(C.line.ok)} ${pct(D.line.okShare)}, ${role(C.line.rest)})`)
    const node = rule('.pot-node')
    expect(node.width).toBe(px(D.node.size))
    expect(node.height).toBe(px(D.node.size))
    expect(node['border-radius']).toBe(px(D.node.size / 2))
    expect(node.border).toBe(`${px(D.node.borderWidth)} solid ${role(C.node.ok)}`)
    expect(node.color).toBe(role(C.node.ok))
    expect(node.background).toBe(role(C.node.background))
    expect(rule('.pot-node.bad').color).toBe(role(C.node.bad))
    expect(rule('.pot-node.bad')['border-color']).toBe(role(C.node.bad))
    const kicker = rule('.pot-kicker')
    expect(kicker['font-size']).toBe(px(D.kicker.fontSize))
    expect(kicker['font-weight']).toBe(String(D.kicker.fontWeight))
    expect(kicker['letter-spacing']).toBe(em(D.kicker.letterSpacing))
    expect(kicker['padding-top']).toBe(px(D.kicker.paddingTop))
    expect(kicker.color).toBe(role(C.kicker.text))
    expect(rule('.pot-identity').gap).toBe(px(D.identity.gap))
    const avatar = rule('.pot-identity .avatar')
    expect(avatar.width).toBe(px(D.identity.avatarSize))
    expect(avatar.height).toBe(px(D.identity.avatarSize))
    expect(avatar['border-radius']).toBe(px(D.identity.avatarRadius))
    expect(avatar['font-size']).toBe(px(D.identity.avatarFontSize))
    expect(rule('.pot-identity-text').gap).toBe(px(D.identity.textGap))
    const name = rule('.pot-name')
    expect(name['font-size']).toBe(px(D.name.fontSize))
    expect(name['font-weight']).toBe(String(D.name.fontWeight))
    expect(name.gap).toBe(px(D.name.gap))
    expect(name['line-height']).toBe(String(D.name.lineHeight))
    expect(rule('.pot-name svg').color).toBe(role(C.nameIcon.color))
    const facts = rule('.pot-facts')
    expect(facts.gap).toBe(px(D.facts.gap))
    expect(facts['font-size']).toBe(px(D.facts.fontSize))
    expect(facts.color).toBe(role(C.facts.text))
    expect(rule('.pot-facts.column').gap).toBe(px(D.facts.columnGap))
    expect(rule('.pot-facts a').gap).toBe(px(D.facts.linkGap))
    expect(rule('.pot-provenance')['font-size']).toBe(px(D.provenance.fontSize))
    expect(rule('.pot-provenance').color).toBe(role(C.provenance.text))
  })

  it('a section, its rows, the roles, the tags and the claims', () => {
    const s = D.section
    expect(rule('.pot-section')['border-top']).toBe(`1px solid ${role(C.section.border)}`)
    expect(rule('.pot-section')['padding-top']).toBe(px(s.paddingTop))
    const title = rule('.pot-section h3')
    expect(title.margin).toBe(`0 0 ${px(s.titleMarginBottom)}`)
    expect(title['font-size']).toBe(px(s.titleFontSize))
    expect(title['font-weight']).toBe(String(s.titleWeight))
    expect(title['letter-spacing']).toBe(em(s.titleSpacing))
    expect(title.gap).toBe(px(s.titleGap))
    expect(title.color).toBe(role(C.section.title))
    const count = rule('.pot-count')
    expect(count['min-width']).toBe(px(D.count.minWidth))
    expect(count.height).toBe(px(D.count.height))
    expect(count.padding).toBe(`0 ${px(D.count.paddingX)}`)
    expect(count['border-radius']).toBe(px(D.count.radius))
    expect(count['font-size']).toBe(px(D.count.fontSize))
    expect(count.background).toBe(tint(C.count.background, D.count.tint))
    expect(count.color).toBe(role(C.count.text))
    const row = rule('.pot-row')
    expect(row.gap).toBe(px(D.row.gap))
    expect(row.padding).toBe(`${px(D.row.paddingY)} 0`)
    expect(row['font-size']).toBe(px(D.row.fontSize))
    expect(rule('.pot-row-title')['font-weight']).toBe(String(D.row.titleWeight))
    expect(rule('.pot-row-title').gap).toBe(px(D.row.titleGap))
    const valid = rule('.pot-valid')
    expect(valid.gap).toBe(px(D.valid.gap))
    expect(valid['font-size']).toBe(px(D.valid.fontSize))
    expect(valid['font-weight']).toBe(String(D.valid.fontWeight))
    expect(valid.color).toBe(role(C.valid.ok))
    expect(rule('.pot-valid.bad').color).toBe(role(C.valid.bad))
    const r = rule('.role')
    expect(r['font-size']).toBe(px(D.role.fontSize))
    expect(r['font-weight']).toBe(String(D.role.fontWeight))
    expect(r['letter-spacing']).toBe(em(D.role.letterSpacing))
    expect(r.padding).toBe(`${px(D.role.paddingY)} ${px(D.role.paddingX)}`)
    expect(r['border-radius']).toBe(px(D.role.radius))
    expect(r.background).toBe(tint(C.role.text, D.role.tint))
    expect(r.color).toBe(role(C.role.text))
    expect(rule('.role-ecosystem').background).toBe(tint(C.role.ecosystem, D.role.ecosystemTint))
    expect(rule('.role-ecosystem').color).toBe(role(C.role.ecosystem))
    const tag = rule('.tag')
    expect(tag['font-size']).toBe(px(D.tag.fontSize))
    expect(tag['font-weight']).toBe(String(D.tag.fontWeight))
    expect(tag['border-radius']).toBe(px(D.tag.radius))
    expect(tag.padding).toBe(`${px(D.tag.paddingY)} ${px(D.tag.paddingX)}`)
    expect(tag.background).toBe(tint(C.tag.text, D.tag.tint))
    expect(tag.color).toBe(role(C.tag.text))
    const claims = rule('.pot-claims')
    expect(claims.margin).toBe(`${px(D.claims.marginTop)} 0 0`)
    expect(claims.gap).toBe(`${px(D.claims.rowGap)} ${px(D.claims.columnGap)}`)
    expect(claims['font-size']).toBe(px(D.claims.fontSize))
    expect(rule('.pot-claims dt').color).toBe(role(C.claims.key))
    expect(rule('.pot-endpoint code')['font-size']).toBe(px(D.endpoint.fontSize))
    expect(rule('.pot-actions').gap).toBe(px(D.actions.gap))
    expect(rule('.pot-actions')['padding-top']).toBe(px(D.actions.paddingTop))
  })
})

describe('the English wording is the shared one', () => {
  it('the card', () => {
    for (const [key, text] of Object.entries(PROOF_OF_TRUST_COPY)) expect(at(en.pot, key), key).toBe(text)
  })
  it('the verdicts and their reasons', () => {
    for (const [key, text] of Object.entries(TRUST_COPY)) expect(at(en.trust, key), key).toBe(text)
  })
})
